def _graph(*, reject_raised=False):
    from tests.fixtures.program_async_competition_graphs import async_competition_program
    return async_competition_program(reject_raised=reject_raised, known_association=True)[0]


def _row(graph):
    rows = tuple(row for row in graph.protocol_operations
                 if type(row.contract) is AdmissionPredicate
                 and type(row.contract.subject) is SessionOccupancyCondition)
    assert len(rows) == 1
    return rows[0]


def _subject(document):
    rows = tuple(row['contract']['subject'] for row in document['protocol_operations']
        if row['contract'].get('kind') == 'PROTOCOL_ADMISSION_PREDICATE'
        and row['contract']['subject'].get('kind') == 'SESSION_OCCUPANCY_CONDITION')
    assert len(rows) == 1
    return rows[0]


@pytest.mark.parametrize('reject_raised', (False, True), ids=('own-normal', 'own-raise'))
def test_program24_roundtrip_keeps_the_original_body_read_and_full_competition_graph(reject_raised):
    graph = _graph(reject_raised=reject_raised)
    require_valid(graph)
    row = _row(graph)
    operation = next(item for item in graph.operations if item.id == row.operation)
    owned = {use.id: use for use in operation.uses}
    assert row.contract.subject.body_use in owned
    assert all(site.operation == operation.id for site in row.contract.subject.state_sites)
    assert codec._has_session_occupancy_capability(graph)
    wire = codec.dumps(graph)
    document = json.loads(wire)
    assert codec.SCHEMA_VERSION == 26 and document['schema_version'] == 24
    assert execution_codec.SCHEMA_VERSION == 8
    assert set(document) == ({field.name for field in fields(ProgramGraph)} - {'call_effect_expansions'}) | {'schema', 'schema_version'}
    encoded = _subject(document)
    assert encoded == encode(row.contract.subject, record_tags={
        **PROTOCOL_CONNECTION_RECORD_TAGS,
        ExistingAccess: ('kind', 'EXISTING_ACCESS'),
    })
    assert set(encoded) == {'kind', 'body_use', 'state_sites'}
    assert PROTOCOL_CONNECTION_RECORD_TAGS[SessionOccupancyCondition] == (
        'kind', 'SESSION_OCCUPANCY_CONDITION')
    recovered = codec.loads(wire)
    assert recovered == graph and codec.dumps(recovered) == wire
    assert recovered.operations == graph.operations and recovered.values == graph.values
    assert recovered.async_request_creates == graph.async_request_creates
    assert recovered.session_updates == graph.session_updates
    assert _row(recovered).contract.subject == row.contract.subject


@pytest.mark.parametrize('version', (19, 20, 21, 22, 23))
def test_historical_schemas_reject_the_new_subject_nested_in_an_old_admission_tag(version):
    document = json.loads(codec.dumps(_graph()))
    assert _subject(document)['kind'] == 'SESSION_OCCUPANCY_CONDITION'
    document['schema_version'] = version
    if version < 21:
        del document['exception_matches']
    with pytest.raises((TypeError, ValueError)):
        codec.loads(json.dumps(document))


def test_untagged_new_subject_still_cannot_smuggle_occupancy_into_program23():
    document = json.loads(codec.dumps(_graph()))
    subject = _subject(document)
    del subject['kind']
    document['schema_version'] = 23
    # Historical tags deliberately do not know this subject. Even though its
    # exact untagged shape can be decoded, the semantic capability stays new.
    with pytest.raises(ValueError, match='historical schema cannot contain session occupancy capability'):
        codec.loads(json.dumps(document))


def test_program24_requires_its_explicit_tag_even_when_the_subject_shape_is_exact():
    document = json.loads(codec.dumps(_graph()))
    del _subject(document)['kind']
    with pytest.raises(ValueError):
        codec.loads(json.dumps(document))


@pytest.mark.parametrize('change', (
    'unknown_body_use', 'body_is_state_use', 'missing_read', 'duplicate_read',
    'foreign_read_operation', 'bool_read_index', 'invented_holder', 'invented_truth',
))
def test_occupancy_wire_rejects_wrong_original_ports_and_invented_semantics(change):
    graph = _graph()
    document = json.loads(codec.dumps(graph))
    subject = _subject(document)
    row = _row(graph)
    operation = next(item for item in graph.operations if item.id == row.operation)
    if change == 'unknown_body_use':
        subject['body_use'] = encode(UseID('missing.occupancy.body'))
    elif change == 'body_is_state_use':
        subject['body_use'] = encode(operation.accesses[0].before)
    elif change == 'missing_read':
        subject['state_sites'] = []
    elif change == 'duplicate_read':
        subject['state_sites'].append(dict(subject['state_sites'][0]))
    elif change == 'foreign_read_operation':
        subject['state_sites'][0]['operation'] = encode(OperationID('absent.occupancy.read'))
    elif change == 'bool_read_index':
        subject['state_sites'][0]['index'] = True
    elif change == 'invented_holder':
        subject['holder'] = subject['body_use']
    else:
        subject['truth'] = True
    with pytest.raises((TypeError, ValueError)):
        codec.loads(json.dumps(document))


@pytest.mark.parametrize('graph_kind', ('request', 'await'))
def test_version24_cannot_be_selected_by_an_old_scope_or_an_old_request_predicate(graph_kind):
    if graph_kind == 'request':
        graph, _ = request_state_program()
        assert any(type(row.contract) is AdmissionPredicate
                   and type(row.contract.subject) is RequestStateCondition
                   for row in graph.protocol_operations)
        expected_version = 19
    else:
        graph, _ = await_resume_program(zero_cut=True, extra_creation=False)
        expected_version = 23
    wire = codec.dumps(graph)
    document = json.loads(wire)
    assert document['schema_version'] == expected_version
    assert not codec._has_session_occupancy_capability(graph)
    assert codec.dumps(codec.loads(wire)) == wire
    document['schema_version'] = 24
    document.setdefault('exception_matches', [])
    with pytest.raises(ValueError, match='schema version 24 requires explicit session occupancy capability'):
        codec.loads(json.dumps(document))


def test_deleting_the_occupancy_attachment_preserves_ports_without_claiming_program24():
    graph = _graph()
    row = _row(graph)
    without = replace(graph, protocol_operations=tuple(item for item in graph.protocol_operations if item != row))
    require_valid(without)
    wire = codec.dumps(without)
    assert json.loads(wire)['schema_version'] < 24
    assert not codec._has_session_occupancy_capability(without)
    assert codec.loads(wire).operations == graph.operations
    assert codec.loads(wire).values == graph.values


